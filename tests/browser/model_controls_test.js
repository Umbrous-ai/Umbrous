'use strict';
const assert = require('node:assert/strict');
const { Preferences, isCloud, loginUrl } = require('../../umbrous/web/model-controls');
const records = new Map();
const storage = { getItem: (k) => records.get(k), setItem: (k, v) => records.set(k, v) };
const a = { name: 'codex/a', reasoning_efforts: ['low', 'high'], default_reasoning_effort: 'low', speeds: ['standard', 'fast'] };
const b = { name: 'codex/b', reasoning_efforts: ['medium'], default_reasoning_effort: 'medium', speeds: ['standard'] };
const prefs = new Preferences(storage);
assert.equal(isCloud(a), true);
assert.equal(isCloud({ name: 'local:3b' }), false);
assert.deepEqual(prefs.forModel(a), { reasoning_effort: 'low', speed: 'standard' });
assert.equal(prefs.change(a, 'speed', 'fast'), true);
assert.equal(prefs.change(a, 'reasoning_effort', 'high'), true);
assert.equal(prefs.change(b, 'speed', 'fast'), false);
assert.equal(prefs.change(a, 'token', 'secret'), false);
prefs.choose(a.name);
assert.deepEqual(prefs.forModel(b), { reasoning_effort: 'medium', speed: 'standard' });
const restored = new Preferences(storage);
assert.equal(restored.selected, a.name);
assert.deepEqual(restored.forModel(a), { reasoning_effort: 'high', speed: 'fast' });
assert.equal(restored.supports({ ...a, speeds: ['standard'] }), false);
assert.equal(new Preferences(null).supports(a), true);
for (const raw of ['https://auth.openai.com/oauth/authorize?state=x', 'https://chatgpt.com/auth/login']) assert.ok(loginUrl(raw));
for (const raw of ['http://auth.openai.com/', 'https://evil.test/auth.openai.com', 'https://auth.openai.com.evil.test/', 'https://user@auth.openai.com/', 'https://auth.openai.com:444/', 'https://auth.openai.com\\@evil.test/', 'javascript:alert(1)']) assert.equal(loginUrl(raw), null, raw);
console.log('Model controls: capability validation, scoped persistence, and safe login URLs passed.');
